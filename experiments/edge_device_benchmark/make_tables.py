# -*- coding: utf-8 -*-
"""
Generate LaTeX tables from an on-device BioDINO-Edge benchmark report.

Inputs:
  --report        benchmark_report.json (pulled from the phone)
  --batterystats  batterystats.txt (optional, for energy estimation)
  --uid           app numeric uid (optional, e.g. 10123), to locate the app's power share
  --out           output .tex file

Outputs booktabs tables ready to paste into paper/main_eaai_elsarticle.tex:
  tab:device_spec             hardware / runtime configuration
  tab:device_perf             load time, peak RAM, per-stage latency, end-to-end
  tab:adaptation_breakdown    extraction / covariance / shrinkage / Cholesky / solve
Energy is reported as mJ per inference when batterystats can be attributed to the app;
otherwise it is left as "--" (the reviewer asked for energy "if possible").
"""
import argparse
import json
import re
from pathlib import Path

NOMINAL_BATTERY_V = 3.85  # Li-ion nominal voltage for mAh -> J conversion


def stat(j, key_mean="mean", key_std="std"):
    if not isinstance(j, dict):
        return "--"
    m = j.get(key_mean)
    s = j.get(key_std, 0.0)
    if m is None:
        return "--"
    return f"{m:.2f}$\\pm${s:.2f}"


def single(j, key="mean"):
    if not isinstance(j, dict):
        return "--"
    v = j.get(key)
    return "--" if v is None else f"{v:.2f}"


def num(v, nd=2):
    return "--" if v is None else f"{v:.{nd}f}"


def med(j):
    return single(j, "median")


def p95(j):
    return single(j, "p95")


def parse_energy(batterystats_text, uid, iterations):
    """Best-effort: find the app's estimated mAh in the power-use section."""
    if not batterystats_text or not iterations or iterations <= 0:
        return None
    # Isolate the "Estimated power use (mAh)" block.
    idx = batterystats_text.find("Estimated power use")
    block = batterystats_text[idx: idx + 4000] if idx >= 0 else batterystats_text
    candidates = []
    if uid:
        candidates.append(rf"Uid\s+{uid}\s*:\s*([0-9.]+)")
        if uid >= 10000:
            candidates.append(rf"u0a{uid - 10000}\s*:\s*([0-9.]+)")
    for pat in candidates:
        m = re.search(pat, block)
        if m:
            mah = float(m.group(1))
            joules = mah * 3.6 * NOMINAL_BATTERY_V  # mAh * 3.6 * V = J
            return joules * 1000.0 / iterations      # mJ per inference
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", required=True)
    ap.add_argument("--batterystats", default=None)
    ap.add_argument("--uid", type=int, default=None)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    r = json.loads(Path(args.report).read_text(encoding="utf-8"))
    dev = r.get("device", {})
    load = r.get("model_load", {})
    mem = r.get("memory", {})
    lat = r.get("latency", {})
    sus = r.get("sustained", {})
    adapt = r.get("adaptation", {})

    bs_text = None
    if args.batterystats and Path(args.batterystats).exists():
        bs_text = Path(args.batterystats).read_text(encoding="utf-8", errors="replace")
    energy_mj = parse_energy(bs_text, args.uid, sus.get("iterations", 0))

    lines = []
    lines.append("% Auto-generated by experiments/edge_device_benchmark/make_tables.py")
    lines.append(f"% Source: {Path(args.report).name} | status={r.get('status')} | {r.get('timestamp_utc', '')}")
    lines.append("")

    # ---- Device spec table ----
    lines.append("\\begin{table}[htbp]")
    lines.append("\\centering")
    lines.append("\\caption{On-device edge testbed configuration (physical Android device, CPU-only INT8).}")
    lines.append("\\label{tab:device_spec}")
    lines.append("\\begin{tabular}{ll}")
    lines.append("\\toprule")
    lines.append("Property & Value \\\\")
    lines.append("\\midrule")
    spec_rows = [
        ("Device", f"{dev.get('manufacturer', '')} {dev.get('model', '')}".strip()),
        ("SoC", dev.get("soc", "unknown")),
        ("Android", f"{dev.get('android_release', '')} (API {dev.get('sdk_int', '')})"),
        ("ABI / cores", f"{dev.get('abi', '')} / {dev.get('cores', '')}"),
        ("Total RAM", f"{dev.get('total_ram_mb', '')} MB"),
        ("ONNX Runtime", dev.get("onnxruntime_version", "")),
        ("Threads (intra/inter)", f"{dev.get('cpu_threads_intra', 4)} / {dev.get('cpu_threads_inter', 2)}"),
        ("Precision / delegate", f"{dev.get('quantization', 'INT8')} / CPU (NNAPI off)"),
    ]
    for k, v in spec_rows:
        lines.append(f"{k} & {v} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    # ---- On-device performance table ----
    t1 = lat.get("tier1", {})
    t2 = lat.get("tier2", {})
    lines.append("\\begin{table}[htbp]")
    lines.append("\\centering")
    lines.append("\\caption{Measured on-device performance (mean$\\pm$std over $N$ iterations; median and p95 in ms).}")
    lines.append("\\label{tab:device_perf}")
    lines.append("\\begin{tabular}{lccc}")
    lines.append("\\toprule")
    lines.append("Stage / metric & Mean$\\pm$std & Median & p95 \\\\")
    lines.append("\\midrule")
    lines.append(f"Tier-1 model load (ms) & {num(load.get('tier1_total_ms'))} & -- & -- \\\\")
    if load.get("tier2_available"):
        lines.append(f"Tier-2 model load (ms) & {num(load.get('tier2_total_ms'))} & -- & -- \\\\")
    lines.append(f"Peak RAM, PSS (MB) & {num(mem.get('peak_pss_mb'))} & -- & -- \\\\")
    lines.append("\\midrule")
    perf_rows = [
        ("Preprocess", t1.get("preprocess_ms")),
        ("Tier-1 DINOv2 encoder", t1.get("encoder_ms")),
        ("Shannon gate / route", t1.get("gate_ms")),
        ("Tier-2 incremental (BioCLIP+Fisher)", t2.get("incremental_ms")),
        ("Decision", lat.get("decision_ms")),
        ("Cascade end-to-end", lat.get("cascade_end_to_end_ms")),
        ("Tier-2-on-all end-to-end", lat.get("tier2_on_all_end_to_end_ms")),
    ]
    for name, j in perf_rows:
        lines.append(f"{name} & {stat(j)} & {med(j)} & {p95(j)} \\\\")
    lines.append("\\midrule")
    fe = lat.get("fast_exit_fraction")
    fe_txt = "--" if fe is None else f"{100.0 * fe:.2f}\\%"
    lines.append(f"Fast-exit fraction & {fe_txt} & -- & -- \\\\")
    lines.append(f"Sustained throughput (FPS) & {sus.get('throughput_fps', '--')} & -- & -- \\\\")
    if energy_mj is not None:
        lines.append(f"Energy (mJ/inference) & {energy_mj:.2f} & -- & -- \\\\")
    else:
        lines.append("Energy (mJ/inference) & -- & -- & -- \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    # ---- Adaptation breakdown table ----
    if adapt and "skipped" not in adapt:
        ex = adapt.get("feature_extraction", {})
        lines.append("\\begin{table}[htbp]")
        lines.append("\\centering")
        lines.append("\\caption{Closed-form adaptation cost breakdown on-device ($N=440$, $d=896$, $C=11$). "
                     "The algebraic budget (rows 2--5) is the measured closed-form recalibration cost "
                     "(sub-second, gradient-free); feature extraction is reported separately. "
                     "Algebra timed after a cool-down at stable thermal state.}")
        lines.append("\\label{tab:adaptation_breakdown}")
        lines.append("\\begin{tabular}{lcc}")
        lines.append("\\toprule")
        lines.append("Stage & Mean$\\pm$std (ms) & Complexity \\\\")
        lines.append("\\midrule")
        lines.append(f"Feature extraction (440 views) & {num(ex.get('total_ms'), 1)} & $O(N(C_{{dino}}+C_{{bio}}))$ \\\\")
        lines.append(f"Covariance estimate & {stat(adapt.get('covariance_ms'))} & $O(Nd^2)$ \\\\")
        lines.append(f"Ledoit--Wolf shrinkage & {stat(adapt.get('ledoit_wolf_ms'))} & $O(Nd)$ \\\\")
        lines.append(f"Cholesky factorization & {stat(adapt.get('cholesky_ms'))} & $O(d^3/3)$ \\\\")
        lines.append(f"Projection solve ($W,b$) & {stat(adapt.get('solve_W_ms'))} & $O(Cd^2)$ \\\\")
        lines.append("\\midrule")
        lines.append(f"Algebraic recalibration total & {stat(adapt.get('algebra_total_ms'))} & -- \\\\")
        lines.append(f"Full adaptation (extraction + algebra) & {num(adapt.get('full_adaptation_ms'), 1)} & -- \\\\")
        lines.append("\\bottomrule")
        lines.append("\\end{tabular}")
        lines.append("\\end{table}")
        lines.append("")
        lines.append(f"% Shrinkage intensity alpha = {adapt.get('shrinkage_alpha', '--')}; "
                     f"thermal status start/max/end = {sus.get('thermal_start')}/"
                     f"{sus.get('thermal_max')}/{sus.get('thermal_end')}")
    else:
        lines.append("% Adaptation benchmark skipped (Tier-2 companion not present on device).")

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")
    if energy_mj is not None:
        print(f"Energy estimate: {energy_mj:.2f} mJ/inference (nominal {NOMINAL_BATTERY_V} V)")
    else:
        print("Energy: not attributable from batterystats (reported as '--').")


if __name__ == "__main__":
    main()